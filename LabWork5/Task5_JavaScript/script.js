// инициализируем счетчик кликов по кнопке для задания 5.5.2
let clickCount = 0;

// находим кнопку и привязываем слушатель событий
const button = document.querySelector('.button-class');
const display = document.getElementById('counter-display');

button.addEventListener('click', () => {
    // инкрементируем счетчик при каждом клике
    clickCount++;
    display.textContent = `Кликов: ${clickCount}`;
    
    // выводим лог нажатия — сюда вешается условный брейкпоинт clickCount >= 3
    console.log("Кнопка нажата", clickCount, "раз");
});

// пункт 5.5.2: цикл for от 1 до 100 с выводом чисел кратных 10
console.log("--- Запуск цикла от 1 до 100 (вывод чисел кратных 10) ---");
for (let i = 1; i <= 100; i++) {
    // проверяем делимость на 10 для отладки условного останова
    if (i % 10 === 0) {
        console.log(`[Число кратно 10]: ${i}`);
    }
}

// пункт 5.5.3: демонстрация различных типов сообщений в консоли DevTools
console.log("--- Проверка типов консольных сообщений ---");
// обычный информационный лог
console.log("[INFO] Это стандартное информационное сообщение через console.log");
// предупреждающее сообщение (желтый фон в консоли)
console.warn("[WARN] Внимание! Это предупреждение через console.warn");
// сообщение об ошибке (красный фон со стек-трейсом в консоли)
console.error("[ERROR] Ошибка! Это критическое сообщение через console.error");
